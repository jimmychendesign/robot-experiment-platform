const orderedTranslations = [...translations].sort(([left], [right]) => right.length - left.length);

function translate(value: string, locale: Locale) {
  if (locale === "zh-CN" || !/[\u3400-\u9fff]/.test(value)) return value;
  return orderedTranslations.reduce((result, [source, target]) => result.replaceAll(source, target), value);
}

const translatedAttributes = ["aria-label", "placeholder", "title"] as const;
const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const originalControlValues = new WeakMap<HTMLInputElement | HTMLTextAreaElement, string>();

export function useLocalizedDom(rootRef: RefObject<HTMLElement | null>, locale: Locale) {
  useEffect(() => {
    const root = rootRef.current;
    if (!root) return;

    const isIgnored = (node: Node) => node instanceof Element
      ? Boolean(node.closest("[data-i18n-ignore]"))
      : Boolean(node.parentElement?.closest("[data-i18n-ignore]"));

    const localizeText = (node: Text, refreshOriginal = false) => {
      if (isIgnored(node) || !node.data.trim()) return;
      const knownOriginal = originalText.get(node);
      if (refreshOriginal && node.data !== translate(knownOriginal ?? node.data, locale)) originalText.set(node, node.data);
      else if (!knownOriginal) originalText.set(node, node.data);
      const source = originalText.get(node) ?? node.data;
      const next = translate(source, locale);
      if (node.data !== next) node.data = next;
    };

    const localizeElement = (element: Element, refreshOriginal = false) => {
      if (isIgnored(element)) return;
      const originals = originalAttributes.get(element) ?? new Map<string, string>();
      translatedAttributes.forEach(attribute => {
        const current = element.getAttribute(attribute);
        if (current === null) return;
        const knownOriginal = originals.get(attribute);
        if (!knownOriginal || (refreshOriginal && current !== translate(knownOriginal, locale))) originals.set(attribute, current);
        const next = translate(originals.get(attribute) ?? current, locale);
        if (current !== next) element.setAttribute(attribute, next);
      });
      originalAttributes.set(element, originals);
      if (element instanceof HTMLInputElement || element instanceof HTMLTextAreaElement) {
        const inputType = element instanceof HTMLInputElement ? element.type : "textarea";
        if (!["checkbox", "radio", "time", "date", "datetime-local"].includes(inputType) && element.value) {
          if (!originalControlValues.has(element)) originalControlValues.set(element, element.value);
          const nextValue = translate(originalControlValues.get(element) ?? element.value, locale);
          if (element.value !== nextValue) element.value = nextValue;
        }
      }
    };

    const localizeTree = (node: Node, refreshOriginal = false) => {
      if (node.nodeType === Node.TEXT_NODE) return localizeText(node as Text, refreshOriginal);
      if (!(node instanceof Element) || isIgnored(node)) return;
      localizeElement(node, refreshOriginal);
      const walker = document.createTreeWalker(node, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      let current: Node | null;
      while ((current = walker.nextNode())) {
        if (current.nodeType === Node.TEXT_NODE) localizeText(current as Text, refreshOriginal);
        else localizeElement(current as Element, refreshOriginal);
      }
    };

    localizeTree(root);
    document.documentElement.lang = locale;
    document.title = locale === "en" ? "RobotOps · Experiment Operations Console" : "RobotOps · 实验运营控制台";
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) description.content = locale === "en"
      ? "A unified operations platform for experiment requests, robot scheduling, tester execution, and resource availability."
      : "统一管理实验需求、Robot 排期、Tester 执行与资源可用性的实验运营平台。";

    const rememberUserValue = (event: Event) => {
      const target = event.target;
      if (target instanceof HTMLInputElement || target instanceof HTMLTextAreaElement) originalControlValues.set(target, target.value);
    };
    root.addEventListener("input", rememberUserValue);

    const observer = new MutationObserver(mutations => {
      mutations.forEach(mutation => {
        if (mutation.type === "characterData") localizeText(mutation.target as Text, true);
        else if (mutation.type === "attributes") localizeElement(mutation.target as Element, true);
        else mutation.addedNodes.forEach(node => localizeTree(node));
      });
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes] });
    return () => {
      observer.disconnect();
      root.removeEventListener("input", rememberUserValue);
    };
  }, [locale, rootRef]);
}
